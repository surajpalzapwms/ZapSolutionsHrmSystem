// ── Who is this letter for? ───────────────────────────────────────────────
const resolveStaff = async (req) => {
  const { staffId } = req.query;
  if (staffId && isAdminRole(req.user?.role)) {
    if (!mongoose.Types.ObjectId.isValid(staffId)) {
      throw new ApiError(400, "Invalid staff ID");
    }
    const s = await Staff.findById(staffId).lean();
    if (!s) throw new ApiError(404, "Staff member not found");
    return s;
  }
  const email = req.user?.email?.toLowerCase().trim();
  const s = email ? await Staff.findOne({ email }).lean() : null;
  if (!s) {
    throw new ApiError(
      404,
      "No staff profile is linked to your account yet. Contact your admin.",
    );
  }
  return s;
};

// ── Which letters can this staff member have right now? ────────────────────
// Returns { [type]: { available, date, reason } }
const letterStatus = async (staff) => {
  const joined = staff.date ? new Date(staff.date) : null;
  const issuedMap = new Map(
    (staff.issuedLetters || []).map((l) => [l.type, l]),
  );
  const yes = (date) => ({ available: true, date, reason: "" });
  // Date of a relieving letter: what HR chose when generating it, else the
  // relieving date on the profile.
  const lwd = (type) => {
    const d = issuedMap.get(type)?.details?.lastWorkingDay;
    return d ? new Date(`${d}T00:00:00.000Z`) : staff.relievingDate || null;
  };

  // EVERY letter can be generated by an admin / super admin for ANY staff
  // member — the "Generate letter" form asks for whatever is missing:
  //   • Offer / Joining / Confirmation — joining date, designation, salary…
  //   • Termination — pick any staff member and the last working day
  //     (past, today or a future date).
  //   • Leaving / Experience — the last working day comes from the staff
  //     member's resignation when they resigned; otherwise HR picks any
  //     date (today or a future date for someone still working).
  const eligibility = {
    offer: yes(joined || staff.createdAt || null),
    joining: yes(joined || null),
    confirmation: yes(staff.confirmationDate || null),
    termination: yes(lwd("termination")),
    leaving: yes(lwd("leaving")),
    experience: yes(lwd("experience")),
  };

  // A letter is only ENABLED for the staff member once an admin / super
  // admin has generated (issued) it. `eligible` = HR may generate it;
  // `issued` = HR generated it; `available` = both (staff can open it).
  const out = {};
  for (const type of LETTER_TYPES) {
    const e = eligibility[type];
    const issued = issuedMap.get(type) || null;
    out[type] = {
      eligible: e.available,
      issued: Boolean(issued),
      issuedAt: issued?.issuedAt || null,
      issuedByName: issued?.issuedByName || "",
      available: e.available && Boolean(issued),
      date: e.available && issued ? e.date : null,
      reason: !e.available
        ? e.reason
        : issued
          ? ""
          : "Not generated by HR yet",
    };
  }
  return out;
};

