// services/leaveAutomation.js
//
// Two related pieces of "fill in the gaps automatically" logic that sit on
// top of the existing manual leave-request flow:
//
//   1. Sandwich leave — when a staff member has approved leave on the
//      working day BEFORE a run of holiday/Sunday days AND on the working
//      day AFTER it, the days in between get counted (and deducted) as
//      leave too, of the same type, instead of being a free non-working
//      block that happens to sit between two leave days.
//
//   2. Absent-day auto-leave — a working day that has no attendance record
//      and no leave request at all (staff simply didn't show up and never
//      applied) gets auto-created as an approved Leave once that day is in
//      the past: "paid" if they still have paid balance left at that point
//      in the year, otherwise "unpaid". This is what makes the monthly
//      accrual eligibility check in services/leaveBalance.js meaningful —
//      without it, an un-applied absence would never show up as an
//      "unpaid" day and would never zero out that month's accrual.
//
// Both are best-effort / idempotent: safe to re-run, and never overwrite a
// leave record a staff member (or admin) actually created themselves.
import Leave from "../models/Leave.js";
import Staff from "../models/Staff.js";
import User from "../models/User.js";
import Attendance from "../models/Attendance.js";
import { isHolidayOrSunday, getDayRange } from "./leave.js";
import { getRemainingForType } from "./leaveBalance.js";

const BALANCE_TRACKED_TYPES = ["paid", "sick", "casual"];

const addDaysUTC = (date, days) => {
  const d = new Date(date);
  d.setUTCDate(d.getUTCDate() + days);
  return d;
};

const findLeaveOn = async (userId, date, statuses, session = null) => {
  const { start, end } = getDayRange(date);
  let q = Leave.findOne({
    userId,
    leaveDate: { $gte: start, $lte: end },
    ...(statuses ? { status: { $in: statuses } } : {}),
  });
  if (session) q = q.session(session);
  return q;
};

// Walks forward/backward from `date`, collecting the consecutive run of
// non-working (holiday/Sunday) days immediately adjacent to it, stopping at
// the next/previous *working* day.
const collectNonWorkingBlockForward = async (date) => {
  const block = [];
  let cursor = addDaysUTC(date, 1);
  while ((await isHolidayOrSunday(cursor)).isHoliday) {
    block.push(new Date(cursor));
    cursor = addDaysUTC(cursor, 1);
  }
  return { block, nextWorkingDay: cursor };
};

const collectNonWorkingBlockBackward = async (date) => {
  const block = [];
  let cursor = addDaysUTC(date, -1);
  while ((await isHolidayOrSunday(cursor)).isHoliday) {
    block.unshift(new Date(cursor));
    cursor = addDaysUTC(cursor, -1);
  }
  return { block, prevWorkingDay: cursor };
};

/**
 * Call this right after a leave (`leave` — a saved Leave document) gets
 * approved. Detects whether it now brackets a weekend/holiday block
 * together with another approved leave on the other side, and if so,
 * fills in the sandwiched days with a matching Leave (same leaveType,
 * deducted from that same balance).
 *
 * Only paid/sick/casual sandwich into a balance deduction — unpaid and
 * swap leave never trigger this, since there's no "balance" for the
 * sandwiched days to draw down.
 *
 * Idempotent: skips any day that already has a Leave record of any status.
 */
export const reconcileSandwichLeave = async (leave, session = null) => {
  if (!BALANCE_TRACKED_TYPES.includes(leave.leaveType)) return [];

  const [fwd, bwd] = await Promise.all([
    collectNonWorkingBlockForward(leave.leaveDate),
    collectNonWorkingBlockBackward(leave.leaveDate),
  ]);

  const candidates = [];

  if (fwd.block.length) {
    const bracketing = await findLeaveOn(leave.userId, fwd.nextWorkingDay, ["approved"], session);
    if (bracketing) candidates.push(...fwd.block);
  }
  if (bwd.block.length) {
    const bracketing = await findLeaveOn(leave.userId, bwd.prevWorkingDay, ["approved"], session);
    if (bracketing) candidates.push(...bwd.block);
  }

  const created = [];
  for (const date of candidates) {
    const existing = await findLeaveOn(leave.userId, date, null, session);
    if (existing) continue; // never override any existing record, of any status

    const docs = await Leave.create(
      [
        {
          userId: leave.userId,
          leaveDate: date,
          leaveType: leave.leaveType,
          status: "approved",
          reason: "Sandwich leave (auto-applied)",
          approvedBy: leave.approvedBy,
          approvedAt: new Date(),
          isAutoGenerated: true,
          isSandwich: true,
          sourceLeaveId: leave._id,
        },
      ],
      session ? { session } : {},
    );
    created.push(docs[0]);
  }
  return created;
};

/**
 * Cascade-deletes any sandwich leave day(s) that were generated because of
 * `leaveId`. Call this whenever the source leave is deleted/reversed, so a
 * sandwich day never survives without the request that justified it.
 */
export const cleanupSandwichLeavesFor = async (leaveId, session = null) => {
  const filter = { sourceLeaveId: leaveId };
  let query = Leave.find(filter);
  if (session) query = query.session(session);
  const dependents = await query;
  if (!dependents.length) return 0;
  let del = Leave.deleteMany(filter);
  if (session) del = del.session(session);
  await del;
  return dependents.length;
};

// How far back a single reconciliation pass will look for a staff member,
// bounded so a staff member who joined years ago doesn't trigger a scan of
// their entire history every time this runs. Run this daily (see the
// /reconcile-absences route) and this window never actually matters in
// practice — it only limits how much a big gap (e.g. first time this
// feature runs) can cost in one pass.
const MAX_LOOKBACK_DAYS = 60;

/**
 * For ONE staff member: walks every working day between `fromDate` and
 * `uptoDate` (inclusive) that has neither an Attendance record nor a Leave
 * record of any kind, and auto-creates an approved Leave for it — "paid"
 * if they still had paid balance remaining at that point in time,
 * "unpaid" otherwise. An Attendance record marked "absent" (no clock-in at
 * all, entered by an admin) counts the same as no record.
 *
 * Days are processed oldest-first so each day's balance check reflects the
 * previous day's deduction. Only ever touches days strictly before
 * `uptoDate` is reached — never today or the future.
 */
export const reconcileAbsentDaysForStaff = async (staff, attendanceUserId, uptoDate) => {
  const created = [];
  const relievingDate =
    staff.status === "Relieving" && staff.relievingDate ? new Date(staff.relievingDate) : null;
  const joinDate = staff.date ? new Date(staff.date) : null;

  const earliestPossible = addDaysUTC(uptoDate, -MAX_LOOKBACK_DAYS);
  let cursor = joinDate && joinDate > earliestPossible ? joinDate : earliestPossible;
  const end = relievingDate && relievingDate < uptoDate ? relievingDate : uptoDate;

  // Months (within the scan window) that have at LEAST ONE real Attendance
  // record for this staff member. A month with zero records anywhere in it
  // almost always means attendance simply wasn't being tracked that month
  // (before the staff member started using the system, an import gap,
  // etc.) rather than the staff member being absent every single working
  // day of it. Blanket-marking every working day of such a month "unpaid"
  // was producing huge, wrong absence counts (e.g. 30+ unpaid days in one
  // month) for staff whose attendance just wasn't logged yet. So: a month
  // with zero attendance records is left untouched here entirely — no
  // auto-generated Leave for any day in it — and an admin can still mark
  // individual days as leave/unpaid by hand. A month that has SOME
  // attendance (even a single day) is treated as genuinely tracked, and
  // any other working day within it that's still blank keeps being
  // auto-marked as before.
  const monthsWithAttendance = new Set();
  if (attendanceUserId) {
    const rangeAttendance = await Attendance.find({
      userId: attendanceUserId,
      loginTime: { $gte: cursor, $lte: end },
    })
      .select("loginTime")
      .lean();
    for (const rec of rangeAttendance) {
      const d = new Date(rec.loginTime);
      monthsWithAttendance.add(`${d.getUTCFullYear()}-${d.getUTCMonth()}`);
    }
  }

  while (cursor <= end) {
    const dateToCheck = new Date(cursor);
    cursor = addDaysUTC(cursor, 1);

    const { isHoliday } = await isHolidayOrSunday(dateToCheck);
    if (isHoliday) continue;

    const existingLeave = await findLeaveOn(staff._id, dateToCheck, null);
    if (existingLeave) continue; // a real request (of any status) always wins

    if (attendanceUserId) {
      const monthKey = `${dateToCheck.getUTCFullYear()}-${dateToCheck.getUTCMonth()}`;
      if (!monthsWithAttendance.has(monthKey)) continue; // whole month untracked — leave for admin, don't auto-mark

      const { start, end: dayEnd } = getDayRange(dateToCheck);
      const attendanceRecord = await Attendance.findOne({
        userId: attendanceUserId,
        loginTime: { $gte: start, $lte: dayEnd },
      }).lean();
      if (attendanceRecord && attendanceRecord.attendanceType !== "absent") continue;
    }

    const remainingPaid = await getRemainingForType(
      staff._id,
      staff.date,
      "paid",
      dateToCheck,
      relievingDate,
    );
    const leaveType = remainingPaid >= 1 ? "paid" : "unpaid";

    const docs = await Leave.create([
      {
        userId: staff._id,
        leaveDate: dateToCheck,
        leaveType,
        status: "approved",
        reason: "Auto-marked absence (no attendance or leave request found)",
        approvedAt: new Date(),
        isAutoGenerated: true,
      },
    ]);
    created.push(docs[0]);
  }

  return created;
};

/**
 * Corrects data already created by an earlier version of
 * reconcileAbsentDaysForStaff that didn't have the "whole untracked month"
 * exclusion: deletes any auto-generated absence Leave (isAutoGenerated:
 * true, i.e. never a real staff/admin request) that falls in a month where
 * this staff member has ZERO real Attendance records. Never touches a
 * manually-created Leave, and never touches an auto-generated Leave in a
 * month that genuinely does have some attendance tracked.
 */
export const cleanupAutoLeavesInUntrackedMonths = async (staff, attendanceUserId) => {
  const autoLeaves = await Leave.find({
    userId: staff._id,
    isAutoGenerated: true,
    isSandwich: { $ne: true }, // sandwich days are handled by cleanupSandwichLeavesFor instead
  })
    .select("_id leaveDate")
    .lean();
  if (!autoLeaves.length) return 0;

  const monthsWithAttendance = new Set();
  if (attendanceUserId) {
    const dates = autoLeaves.map((l) => new Date(l.leaveDate));
    const rangeStart = new Date(Math.min(...dates.map((d) => d.getTime())));
    const rangeEnd = new Date(Math.max(...dates.map((d) => d.getTime())));
    rangeEnd.setUTCHours(23, 59, 59, 999);
    const rangeAttendance = await Attendance.find({
      userId: attendanceUserId,
      loginTime: { $gte: rangeStart, $lte: rangeEnd },
    })
      .select("loginTime")
      .lean();
    for (const rec of rangeAttendance) {
      const d = new Date(rec.loginTime);
      monthsWithAttendance.add(`${d.getUTCFullYear()}-${d.getUTCMonth()}`);
    }
  }

  const idsToDelete = [];
  for (const leave of autoLeaves) {
    const d = new Date(leave.leaveDate);
    const monthKey = `${d.getUTCFullYear()}-${d.getUTCMonth()}`;
    // No linked attendance-user at all, or the month has zero tracked
    // attendance either way — the auto-mark shouldn't have happened.
    if (!attendanceUserId || !monthsWithAttendance.has(monthKey)) {
      idsToDelete.push(leave._id);
    }
  }
  if (!idsToDelete.length) return 0;

  await Leave.deleteMany({ _id: { $in: idsToDelete } });
  return idsToDelete.length;
};

/**
 * Runs reconcileAbsentDaysForStaff for every staff member, up through
 * `uptoDate` (defaults to yesterday — a day isn't "absent" until it's
 * over). Meant to be called once a day (see the /reconcile-absences admin
 * route); safe to call more than once since it's idempotent. Also cleans
 * up any previously over-marked auto-absences left over from before the
 * "whole untracked month" exclusion existed.
 */
export const reconcileAllStaffAbsences = async (uptoDate = null) => {
  const end = uptoDate || addDaysUTC(new Date(), -1);
  end.setUTCHours(23, 59, 59, 999);

  const staffList = await Staff.find({}).lean();
  const summary = { staffProcessed: 0, leavesCreated: 0, leavesCleaned: 0, errors: [] };

  for (const staff of staffList) {
    try {
      const user = staff.email
        ? await User.findOne({ email: staff.email.toLowerCase() }).select("_id").lean()
        : null;
      const attendanceUserId = user?._id || null;
      const cleaned = await cleanupAutoLeavesInUntrackedMonths(staff, attendanceUserId);
      const created = await reconcileAbsentDaysForStaff(staff, attendanceUserId, end);
      summary.staffProcessed += 1;
      summary.leavesCreated += created.length;
      summary.leavesCleaned += cleaned;
    } catch (err) {
      summary.errors.push(`${staff.staffName || staff._id}: ${err.message}`);
    }
  }

  return summary;
};
