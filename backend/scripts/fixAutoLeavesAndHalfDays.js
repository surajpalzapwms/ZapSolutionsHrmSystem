// scripts/fixAutoLeavesAndHalfDays.js
//
// One-off repair for data saved by the old code. Fixes three things:
//
//   1. Absences the automatic sweep saved as Sick / Casual / Paid.
//      An automatic absence is now always Unpaid, so these become Unpaid.
//   2. Paid / Sick / Casual leave dated BEFORE the staff member's
//      confirmation date (no entitlement exists yet). These become Unpaid.
//   3. Half Day / Absent markers stored with a login of 00:00 IST
//      (= 18:30 UTC the previous day). Their login is moved to 10:00 IST on
//      the same day, so no screen can read them as the day before.
//
// DRY RUN by default: it only prints what it would change.
//
// Usage (from the backend folder):
//   node scripts/fixAutoLeavesAndHalfDays.js            # preview
//   node scripts/fixAutoLeavesAndHalfDays.js --apply    # make the changes
//
// Uses MONGO_URI from .env, like server.js. Safe to run more than once.

import "dotenv/config";
import mongoose from "mongoose";
import Staff from "../models/Staff.js";
import Leave from "../models/Leave.js";
import Attendance from "../models/Attendance.js";
import { isBeforeConfirmation, istDayKey } from "../services/leave.js";

const APPLY = process.argv.includes("--apply");
const IST_OFFSET_MS = 5.5 * 60 * 60 * 1000;
const BALANCE_TYPES = ["paid", "sick", "casual"];

const run = async () => {
  const MONGO_URI = process.env.MONGO_URI;
  if (!MONGO_URI) {
    console.error("Missing MONGO_URI in .env");
    process.exit(1);
  }
  await mongoose.connect(MONGO_URI, {
    serverSelectionTimeoutMS: 5000,
    socketTimeoutMS: 45000,
  });
  console.log(APPLY ? "APPLY mode — changes will be saved\n" : "DRY RUN — nothing will be saved (add --apply)\n");

  const staffById = new Map(
    (await Staff.find({}).lean()).map((s) => [String(s._id), s]),
  );
  const nameOf = (id) => staffById.get(String(id))?.staffName || String(id);

  // ── 1 + 2: Paid/Sick/Casual that should be Unpaid ─────────────────────
  const candidates = await Leave.find({
    leaveType: { $in: BALANCE_TYPES },
    status: { $in: ["pending", "approved"] },
    isSandwich: { $ne: true },
  })
    .select("_id userId leaveDate leaveType isAutoGenerated")
    .lean();

  const toUnpaid = [];
  for (const lv of candidates) {
    const staff = staffById.get(String(lv.userId));
    const auto = lv.isAutoGenerated === true;
    const preConfirmation = staff ? isBeforeConfirmation(staff, lv.leaveDate) : false;
    if (!auto && !preConfirmation) continue;
    toUnpaid.push(lv);
    console.log(
      `Leave  ${istDayKey(lv.leaveDate)}  ${nameOf(lv.userId).padEnd(24)} ${lv.leaveType} -> unpaid  (${
        auto ? "auto-marked absence" : "before confirmation date"
      })`,
    );
  }

  // ── 3: Half Day / Absent markers saved at 00:00 IST ───────────────────
  const markers = await Attendance.find({
    $or: [{ attendanceType: "half" }, { attendanceType: "absent" }, { status: "absent" }],
    date: { $regex: /^\d{4}-\d{2}-\d{2}$/ },
  })
    .select("_id userId date loginTime")
    .lean();
  const toShift = markers.filter((m) => {
    const ist = new Date(new Date(m.loginTime).getTime() + IST_OFFSET_MS);
    return ist.getUTCHours() === 0 && ist.getUTCMinutes() === 0;
  });
  toShift.forEach((m) =>
    console.log(`Marker ${m.date}  login 00:00 IST -> 10:00 IST  (attendance ${m._id})`),
  );

  console.log(
    `\n${toUnpaid.length} leave day(s) to change to Unpaid, ${toShift.length} Half Day/Absent marker(s) to fix.`,
  );

  if (APPLY) {
    if (toUnpaid.length) {
      await Leave.updateMany(
        { _id: { $in: toUnpaid.map((l) => l._id) } },
        { $set: { leaveType: "unpaid" } },
      );
    }
    for (const m of toShift) {
      // 10:00 IST on the record's own day = 04:30 UTC that day.
      const loginTime = new Date(new Date(`${m.date}T10:00:00.000Z`).getTime() - IST_OFFSET_MS);
      await Attendance.updateOne({ _id: m._id }, { $set: { loginTime } });
    }
    console.log("Done. Restart the backend (or wait 10 minutes) so calendars recompute.");
  }

  await mongoose.disconnect();
};

run().catch(async (err) => {
  console.error("Failed:", err);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
