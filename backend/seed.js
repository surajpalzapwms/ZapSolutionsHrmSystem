// scripts/reclassifyAutoLeaves.js
//
// One-off correction for data created by the old absence-reconciliation
// bug: `processAbsentRun` used to only ever check the Paid balance for an
// auto-marked absent day, falling straight to Unpaid if Paid was used up —
// it never considered Sick or Casual at all. That's now fixed going
// forward (see services/leaveAutomation.js), but every day it already
// auto-marked as "paid" or "unpaid" before the fix is still sitting on the
// wrong type, which both under-reports Sick/Casual usage AND wrongly
// exhausts the Paid balance for the year (blocking later legitimate Paid
// requests, including Excel imports).
//
// This script re-examines every AUTO-GENERATED (isAutoGenerated: true),
// non-sandwich, approved Leave record currently typed "paid" or "unpaid",
// oldest date first per staff member, and — using the exact same priority
// the rest of the app uses (Sick, then Casual, then Paid, then Unpaid) —
// reassigns it to whichever type actually had room at that historical
// date. Manually-requested leave (isAutoGenerated: false/undefined) is
// NEVER touched. Records are processed oldest-first per staff so each
// reassignment is reflected in the balance check for the next record.
//
// SAFE BY DEFAULT: runs as a dry run (prints what it WOULD change) unless
// you pass --apply.
//
// Usage (from the backend/ folder):
//   node scripts/reclassifyAutoLeaves.js                          (dry run, all staff)
//   node scripts/reclassifyAutoLeaves.js --apply                  (apply, all staff)
//   node scripts/reclassifyAutoLeaves.js ravi.mishra@company.com  (dry run, one staff)
//   node scripts/reclassifyAutoLeaves.js ravi.mishra@company.com --apply
//
// Requires the same MONGO_URI your server already uses (reads it from
// .env via dotenv, exactly like server.js does).

import "dotenv/config";
import mongoose from "mongoose";
import Staff from "./models/Staff.js";
import Leave from "./models/Leave.js";
import { getRemainingForType } from "./services/leaveBalance.js";

const fmtDate = (d) => new Date(d).toISOString().slice(0, 10);

const run = async () => {
  const args = process.argv.slice(2);
  const apply = args.includes("--apply");
  const identifier = args.find((a) => !a.startsWith("--"));

  const MONGO_URI = process.env.MONGO_URI;
  if (!MONGO_URI) {
    console.error("❌ Missing MONGO_URI in .env");
    process.exit(1);
  }

  await mongoose.connect(MONGO_URI, {
    serverSelectionTimeoutMS: 5000,
    socketTimeoutMS: 45000,
  });
  console.log(`✅ MongoDB connected — mode: ${apply ? "APPLY (writing changes)" : "DRY RUN (no changes will be saved)"}\n`);

  let staffFilter = {};
  if (identifier) {
    const staff = mongoose.Types.ObjectId.isValid(identifier)
      ? await Staff.findById(identifier).lean()
      : await Staff.findOne({ email: identifier.toLowerCase().trim() }).lean();
    if (!staff) {
      console.error(`❌ No staff found for "${identifier}"`);
      await mongoose.disconnect();
      process.exit(1);
    }
    staffFilter = { _id: staff._id };
    console.log(`Scoped to: ${staff.staffName} (${staff.email || staff._id})\n`);
  }

  const staffList = await Staff.find(staffFilter).lean();
  const staffById = new Map(staffList.map((s) => [String(s._id), s]));

  const candidates = await Leave.find({
    userId: { $in: staffList.map((s) => s._id) },
    isAutoGenerated: true,
    isSandwich: { $ne: true },
    status: "approved",
    leaveType: { $in: ["paid", "unpaid"] },
  })
    .sort({ userId: 1, leaveDate: 1 })
    .lean();

  console.log(`Found ${candidates.length} auto-generated Paid/Unpaid record(s) to re-examine.\n`);

  const summary = { unchanged: 0 };
  const bump = (from, to) => {
    const key = `${from} → ${to}`;
    summary[key] = (summary[key] || 0) + 1;
  };

  for (const rec of candidates) {
    const staff = staffById.get(String(rec.userId));
    if (!staff) continue; // shouldn't happen given the $in filter above

    const confirmationDate = staff.confirmationDate ?? null;
    const relievingDate = staff.status === "Relieved" ? staff.relievingDate : null;
    const dayValue = rec.dayValue ?? 1;
    const asOf = new Date(rec.leaveDate);

    let newType = rec.leaveType; // default: no change
    for (const candidateType of ["sick", "casual", "paid"]) {
      if (candidateType === rec.leaveType) break; // already at-or-past this priority tier, stop looking
      const remaining = await getRemainingForType(
        rec.userId,
        confirmationDate,
        candidateType,
        asOf,
        relievingDate,
      );
      if (remaining >= dayValue) {
        newType = candidateType;
        break;
      }
    }

    if (newType !== rec.leaveType) {
      console.log(
        `  ${staff.staffName.padEnd(20)} ${fmtDate(rec.leaveDate)}  ${rec.leaveType} → ${newType}  (dayValue=${dayValue})`,
      );
      bump(rec.leaveType, newType);
      if (apply) {
        await Leave.updateOne({ _id: rec._id }, { $set: { leaveType: newType } });
      }
    } else {
      summary.unchanged++;
    }
  }

  console.log("\n── Summary ──────────────────────────────────────────");
  Object.entries(summary).forEach(([k, v]) => console.log(`  ${k}: ${v}`));
  if (!apply) {
    console.log(
      "\nThis was a DRY RUN — nothing was saved. Re-run with --apply once this looks right.",
    );
  } else {
    console.log("\n✅ Changes applied.");
  }

  await mongoose.disconnect();
};

run().catch(async (err) => {
  console.error("❌ Script failed:", err);
  await mongoose.disconnect();
  process.exit(1);
});