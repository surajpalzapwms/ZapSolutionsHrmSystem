const ZAP_DEFAULT_ADDRESS = "[Kandivali] | [Mumbai, Maharashtra State, 400101]";

/** "Street, City, State 400101" */
export const fullAddress = (p) =>
  [p.address, [p.city, p.state].filter(Boolean).join(", "), p.postalCode]
    .map((x) => String(x || "").trim())
    .filter(Boolean)
    .join(", ");

const letterCompany = async () => {
  const base = await getCompanyProfile();
  const assets = await getCompanyAssets();
  const zap = /^\s*zap\b/i.test(base.name || "");
  const signatory = [base.signatoryName, base.signatoryTitle].filter(Boolean).join(", ");
  return {
    ...base,
    // Only the company's own tagline on official letters (not the default).
    tagline: currentCompany()?.tagline || "",
    // PDFs need the image bytes: an uploaded logo is passed as a data URL.
    logoUrl: assets.logoDataUrl || "",
    signatureImage: assets.signature,
    stampImage: assets.stamp,
    email: base.email || (zap ? process.env.COMPANY_EMAIL || "admin@zapwms.com" : ""),
    address: fullAddress(base) || (zap ? process.env.COMPANY_ADDRESS || ZAP_DEFAULT_ADDRESS : ""),
    signatory: signatory || (zap ? process.env.COMPANY_SIGNATORY || "" : ""),
    // "CR No.: 1010… · VAT No.: 3…" printed in the letter footer.
    legalLine: (base.legalIdList || [])
      .filter((x) => x.print)
      .map((x) => `${x.label}: ${x.value}`)
      .join("   ·   "),
  };
};

// Monthly salary in force on a date, from Staff Basic Payroll (+ history).
const salaryLookup = async (staffId) => {
  const rec = await StaffBasicPayroll.findOne({ employeeId: staffId }).lean().catch(() => null);
  if (!rec) return () => null;
  const history = (rec.salaryHistory || [])
    .filter((h) => h?.effectiveFrom)
    .sort((a, b) => new Date(a.effectiveFrom) - new Date(b.effectiveFrom));
  return (date) => {
    const t = new Date(date).getTime();
    let amount = history.length ? history[0].basicSalary : rec.currentBasicSalary;
    for (const h of history) if (new Date(h.effectiveFrom).getTime() <= t) amount = h.basicSalary;
    return Number(amount) || null;
  };
};

// Aadhaar / PAN numbers typed in under My Documents.
const idNumbers = async (staffId) => {
  const docs = await StaffDocument.find({ staff: staffId, type: { $in: ["aadhaar", "pan"] } })
    .select("type number")
    .lean()
    .catch(() => []);
  const by = Object.fromEntries(docs.map((d) => [d.type, d.number || ""]));
  const a = String(by.aadhaar || "").replace(/\s+/g, "");
  return {
    aadhaar: /^\d{12}$/.test(a) ? a.replace(/(\d{4})(?=\d)/g, "$1 ") : a,
    pan: by.pan || "",
  };
};

const COMPANY_LAYOUT = {
  offer: renderOfferLetter,
  joining: renderJoiningLetter,
  confirmation: renderConfirmationLetter,
};

// The staff member's latest resignation that is still in force (approved
// first, then pending) — its last working day goes on the relieving letters.
const latestResignation = async (staffId) => {
  const list = await Resignation.find({ userId: staffId, status: { $in: ["approved", "pending"] } })
    .sort({ createdAt: -1 })
    .select("status lastWorkingDay")
    .lean()
    .catch(() => []);
  return list.find((r) => r.status === "approved") || list[0] || null;
};

// Everything a letter's PDF and "Generate letter" form need.
// `answers` (optional) = what HR just typed in the form.
const letterValues = async (type, staff, answers = null) => {
  const relieving = RELIEVING_LETTERS.includes(type);
  const [co, salaryAt, ids, resignation] = await Promise.all([
    letterCompany(),
    relieving ? () => null : salaryLookup(staff._id),
    relieving ? {} : idNumbers(staff._id),
    relieving ? latestResignation(staff._id) : null,
  ]);
  // Values typed for THIS letter last time win; personal details typed for
  // another letter of the same person (Aadhaar, PAN, e-mail, current
  // address, signatory) are reused instead of being asked again.
  const SHARED = ["aadhaar", "pan", "email", "currentAddress", "signatory"];
  const letters = staff.issuedLetters || [];
  const fromOthers = {};
  for (const l of letters) {
    if (l.type === type || !l.details) continue;
    for (const k of SHARED) if (l.details[k]) fromOthers[k] = l.details[k];
  }
  const own = letters.find((l) => l.type === type)?.details || {};
  const saved = { ...fromOthers, ...Object.fromEntries(Object.entries(own).filter(([, v]) => v !== "" && v != null)) };
  const current = currentValues(type, { staff, saved, salaryAt, ids, company: co, resignation });
  if (!answers) return { values: current, co, salaryAt, resignation };
  return { ...applyAnswers(type, current, answers, staff), co, salaryAt, resignation };
};

// @route GET /api/hrm/letters/staff/:staffId/:type/form   (admin / super admin)
// The "Generate letter" form: every field with its current value, and which
// ones are still MISSING (only those need to be asked).
export const getLetterForm = asyncHandler(async (req, res) => {
  const type = checkType(req.params.type);
  const staff = await findStaffForAdmin(req.params.staffId);
  if (!FORM_LETTERS.includes(type)) {
    return res.json({ success: true, data: { type, title: TITLES[type], fields: [], missingCount: 0 } });
  }
  const { values, resignation } = await letterValues(type, staff.toObject());
  const hints = {};
  if (RELIEVING_LETTERS.includes(type)) {
    hints.lastWorkingDay = resignation?.lastWorkingDay
      ? `From ${staff.staffName}'s ${resignation.status} resignation: ${fmtDate(resignation.lastWorkingDay)}. You can pick any other date — past, today or future.`
      : "No resignation on record — pick any date: today, a past date or a future date.";
  }
  const fields = describeFields(type, values, hints);
  res.json({
    success: true,
    data: {
      type,
      title: TITLES[type],
      fields,
      missingCount: fields.filter((f) => f.missing).length,
    },
  });
});

// @route GET /api/hrm/letters/:type/download
export const downloadLetter = asyncHandler(async (req, res) => {
  const type = String(req.params.type || "").toLowerCase();
  if (!LETTER_TYPES.includes(type)) {
    throw new ApiError(400, "Unknown letter type");
  }

  const staff = await resolveStaff(req);
  const status = (await letterStatus(staff))[type];
  // Admins may download/preview any letter the profile is eligible for;
  // staff only get letters an admin has generated.
  const isAdmin = isAdminRole(req.user?.role) && req.query.staffId;
  if (isAdmin ? !status.eligible : !status.available) {
    throw new ApiError(400, `${TITLES[type]} is not available: ${status.reason}`);
  }

  const fileName = `${TITLES[type].replace(/\s+/g, "_")}-${(staff.staffName || "staff").replace(/\s+/g, "_")}.pdf`;

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename="${fileName}"`);

  // Offer / Joining / Confirmation: the company's own letter layout.
  if (COMPANY_LAYOUT[type]) {
    const { values, co, salaryAt } = await letterValues(type, staff);
    const letterDate = new Date(`${values.letterDate}T00:00:00.000Z`);
    const ldoc = COMPANY_LAYOUT[type](PDFDocument, {
      staff: staffForLetter(staff, values),
      company: co,
      salaryAt,
      salaryRows: values.salaryRows,
      salary: values.salary === "" ? null : values.salary,
      extra: { aadhaar: values.aadhaar, pan: values.pan },
      letterDate,
      trialDays: Number(values.trialDays) || 10,
      signatory: values.signatory || "",
    });
    ldoc.on("error", (err) => {
      console.error("[letter] PDF stream error:", err);
      if (!res.writableEnded) res.end();
    });
    ldoc.pipe(res);
    ldoc.end();
    return;
  }

  // Termination / Leaving / Experience: the details HR entered (last
  // working day, name, Mr./Ms., reason…) on top of the profile.
  const { values: rv, co: company } = await letterValues(type, staff);
  if (!rv.lastWorkingDay) {
    res.removeHeader("Content-Disposition");
    res.setHeader("Content-Type", "application/json");
    throw new ApiError(400, `Choose the last working day first — click Generate on the ${TITLES[type]}.`);
  }
  const lstaff = staffForLetter(staff, rv);
  const printedDate = rv.letterDate ? new Date(`${rv.letterDate}T00:00:00.000Z`) : status.date || new Date();

  const doc = new PDFDocument({ size: "A4", margin: 0 });
  doc.on("error", (err) => {
    console.error("[letter] PDF stream error:", err);
    if (!res.writableEnded) res.end();
  });
  doc.pipe(res);

  // Company colours (navy / gold when the company has not chosen any).
  const NAVY = company.sidebarColor || "#1B3A5C";
  const GOLD = company.primaryColor || "#C9A24B";
  const TEXT = "#1B1B1B";
  const W = doc.page.width;
  const H = doc.page.height;
  const mx = 60;
  const cw = W - mx * 2;
  const logoImg = (() => {
    const m = /^data:image\/(png|jpe?g);base64,(.+)$/i.exec(company.logoUrl || "");
    return m ? Buffer.from(m[2], "base64") : null;
  })();

  // Header band: logo on a white tile + company name
  doc.rect(0, 0, W, 80).fill(NAVY);
  let nameX = mx;
  if (logoImg) {
    try {
      doc.roundedRect(mx - 6, 12, 62, 56, 6).fill("#FFFFFF");
      doc.image(logoImg, mx - 2, 16, { fit: [54, 48], align: "center", valign: "center" });
      nameX = mx + 66;
    } catch {
      nameX = mx; // unreadable image: name only
    }
  }
  doc
    .font("Helvetica-Bold")
    .fontSize(18)
    .fillColor("#FFFFFF")
    .text(company.name, nameX, 28, { width: cw - (nameX - mx) });
  if (company.tagline) {
    doc
      .font("Helvetica")
      .fontSize(9)
      .fillColor("#DDE6F0")
      .text(company.tagline, nameX, 52, { width: cw - (nameX - mx) });
  }

  // Title
  doc
    .font("Helvetica-Bold")
    .fontSize(20)
    .fillColor(NAVY)
    .text(TITLES[type].toUpperCase(), mx, 112, { width: cw, align: "center" });
  doc
    .moveTo(mx, 142)
    .lineTo(W - mx, 142)
    .strokeColor(GOLD)
    .lineWidth(1.5)
    .stroke();

  // Date + reference
  let y = 160;
  doc.font("Helvetica").fontSize(10).fillColor(TEXT);
  doc.text(`Date: ${fmtDate(printedDate)}`, mx, y, {
    width: cw,
    align: "right",
  });
  doc.text(
    `Ref: ${(company.shortName || "HR").toUpperCase()}/${type.toUpperCase()}/${staff.staffId || String(staff._id).slice(-6)}`,
    mx,
    y,
    { width: cw },
  );
  y += 30;

  // Addressee (not for "To whom it may concern")
  if (type !== "experience") {
    doc.font("Helvetica-Bold").text(titledName(lstaff), mx, y);
    y += 14;
    doc.font("Helvetica");
    if (staff.staffId) {
      doc.text(`Employee ID: ${staff.staffId}`, mx, y);
      y += 14;
    }
    if (lstaff.designation) {
      doc.text(lstaff.designation, mx, y);
      y += 14;
    }
    if (staff.email) {
      doc.text(staff.email, mx, y);
      y += 14;
    }
    y += 12;
    doc.font("Helvetica-Bold").text(`Subject: ${TITLES[type]}`, mx, y);
    y += 26;
  }

  // Body
  const paras = letterBody(type, lstaff, company);
  paras.forEach((p, i) => {
    const isHeading = type === "experience" && i === 0;
    doc
      .font(isHeading ? "Helvetica-Bold" : "Helvetica")
      .fontSize(11)
      .fillColor(TEXT)
      .text(p, mx, y, {
        width: cw,
        align: isHeading ? "center" : "justify",
        lineGap: 3,
      });
    y = doc.y + 14;
  });

  // Sign-off
  y += 20;
  doc.font("Helvetica").fontSize(11).text("Sincerely,", mx, y);
  y += 16;
  doc.font("Helvetica-Bold").text(`For ${company.name}`, mx, y);
  y += 18;
  // Signature and company stamp (uploaded on the company profile).
  if (company.signatureImage) {
    try {
      doc.image(company.signatureImage, mx, y, { fit: [150, 40] });
    } catch {
      /* unreadable image */
    }
  }
  if (company.stampImage) {
    try {
      doc.image(company.stampImage, mx + 190, y - 18, { fit: [80, 80] });
    } catch {
      /* unreadable image */
    }
  }
  y += 42;
  doc
    .moveTo(mx, y)
    .lineTo(mx + 160, y)
    .strokeColor("#999999")
    .lineWidth(0.8)
    .stroke();
  y += 6;
  doc.font("Helvetica-Bold").fontSize(10).fillColor(TEXT).text(company.signatoryName || "Authorized Signatory", mx, y);
  y += 13;
  doc.font("Helvetica").text(company.signatoryTitle || "Human Resources", mx, y);

  // Footer: address, registration numbers, contact
  const footerLines = [
    company.address,
    company.legalLine,
    [company.phone, company.email, company.website].filter(Boolean).join("   ·   "),
  ].filter(Boolean);
  const footerH = 22 + footerLines.length * 11;
  doc.rect(0, H - footerH, W, footerH).fill(NAVY);
  doc.font("Helvetica").fontSize(8).fillColor("#FFFFFF");
  footerLines.forEach((line, i) => {
    doc.text(line, mx, H - footerH + 8 + i * 11, { width: cw, align: "center", lineBreak: false, ellipsis: true });
  });
  doc
    .fontSize(7)
    .fillColor("#DDE6F0")
    .text("This is a system-generated letter.", mx, H - 14, { width: cw, align: "center", lineBreak: false });

  doc.end();
});

// ── Admin: generate (issue) / revoke a letter for a staff member ──────────
const findStaffForAdmin = async (staffId) => {
  if (!mongoose.Types.ObjectId.isValid(staffId)) {
    throw new ApiError(400, "Invalid staff ID");
  }
  const staff = await Staff.findById(staffId);
  if (!staff) throw new ApiError(404, "Staff member not found");
  return staff;
};

const checkType = (raw) => {
  const type = String(raw || "").toLowerCase();
  if (!LETTER_TYPES.includes(type)) throw new ApiError(400, "Unknown letter type");
  return type;
};

const listFor = async (staff) => {
  const status = await letterStatus(staff);
  return LETTER_TYPES.map((type) => ({ type, title: TITLES[type], ...status[type] }));
};

