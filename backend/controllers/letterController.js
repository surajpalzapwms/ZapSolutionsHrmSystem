// ── Letter wording ────────────────────────────────────────────────────────
const letterBody = (type, staff, company) => {
  const future = staff.relievingDate && ymd(staff.relievingDate) > ymd(new Date());
  const name = titledName(staff);
  const pr = pronouns(staff.gender);
  const team = staff.projectName ? ` in the ${staff.projectName} team` : "";
  const joined = fmtDate(staff.date);
  const lastDay = fmtDate(staff.relievingDate);
  const confirmedOn = fmtDate(staff.confirmationDate);
  const firstStage = staff.internshipEndDate ? "internship" : "probation";
  const months = staff.internshipEndDate
    ? staff.internshipMonths
    : staff.probationMonths;
  const service = serviceLength(staff.date, staff.relievingDate);

  switch (type) {
    case "offer":
      return [
        `Dear ${name},`,
        `We are pleased to offer you a position with ${company.name}${team}. Your date of joining will be ${joined}.`,
        `You will initially be on ${firstStage} for a period of ${months || 3} month(s). On successful completion, your employment will be reviewed for confirmation as per company policy.`,
        `Your compensation, working hours and other terms of employment will be as per company policy and will be shared with you by the HR team.`,
        `We look forward to welcoming you to ${company.name}. Please sign and return a copy of this letter as a token of your acceptance.`,
      ];
    case "joining":
      return [
        `Dear ${name},`,
        `This is to confirm that you have joined ${company.name}${team} on ${joined}.`,
        `Your employee ID is ${staff.staffId || "as issued by HR"}. You are required to follow all the rules, policies and code of conduct of the company in force from time to time.`,
        `We welcome you to the team and wish you a long and successful career with us.`,
      ];
    case "confirmation":
      return [
        `Dear ${name},`,
        `Further to your appointment with ${company.name} on ${joined}, we are pleased to inform you that, based on a review of your performance, your services have been confirmed with effect from ${confirmedOn}.`,
        `All other terms and conditions of your employment remain unchanged.`,
        `We appreciate your contribution and look forward to your continued association with the company.`,
      ];
    case "termination":
      return [
        `Dear ${name},`,
        `This letter is to inform you that your employment with ${company.name} ${future ? "will stand terminated" : "stands terminated"} with effect from ${lastDay}${future ? ", which will be your last working day" : ""}.`,
        ...(staff.terminationReason
          ? [`This decision has been taken for the following reason: ${staff.terminationReason.replace(/\.\s*$/, "")}.`]
          : []),
        `You are requested to hand over all company property, documents and access in your possession${future ? " on or before your last working day" : ""}, and to complete the exit formalities with the HR department.`,
        `Your full and final settlement, if any, will be processed as per company policy.`,
      ];
    case "leaving":
      return [
        `Dear ${name},`,
        future
          ? `This is with reference to your resignation. We hereby confirm that you will be relieved from your duties at ${company.name} at the close of business hours on ${lastDay}, which will be your last working day.`
          : `This is with reference to your resignation. We hereby confirm that you have been relieved from your duties at ${company.name} at the close of business hours on ${lastDay}.`,
        `You ${future ? "are" : "were"} employed with us from ${joined} to ${lastDay}. Your full and final settlement will be processed as per company policy.`,
        `We thank you for your contribution and wish you success in your future endeavours.`,
      ];
    case "experience":
      return [
        `TO WHOM IT MAY CONCERN`,
        `This is to certify that ${name}${staff.staffId ? ` (Employee ID: ${staff.staffId})` : ""}${staff.designation ? `, ${staff.designation},` : ""} ${future ? "is employed" : "was employed"} with ${company.name}${team} from ${joined} to ${lastDay}${service ? `, a period of ${service}` : ""}.`,
        `During this tenure we found ${pr.him} to be sincere, hardworking and dedicated. ${pr.His} conduct with us was good.`,
        `We wish ${pr.him} all the best in ${pr.his} future endeavours.`,
      ];
    default:
      return [];
  }
};

