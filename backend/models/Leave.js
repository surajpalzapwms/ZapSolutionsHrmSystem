import mongoose from "mongoose";

const leaveSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Staff",
      required: true,
    },
    leaveDate: {
      type: Date,
      required: true,
    },
    reason: {
      type: String,
      required: true,
    },batchId: {
      type: String,
      index: true,
    },
    leaveType: {
      type: String,
      // "sick" and "casual" are balance-tracked leave types (see LeavePolicy /
      // services/leaveBalance.js) exactly like "paid" — they were previously
      // missing from this enum, which silently made every sick/casual leave
      // application fail model validation even though the balance-checking
      // code elsewhere already accounted for them.
      enum: ["paid", "unpaid", "swapleave", "sick", "casual"],
      default: "unpaid",
    },
    // How many days this single Leave record actually represents. Almost
    // always 1 (a normal full-day leave). 0.5 for a half-day leave applied
    // from the Half Day toggle in the apply-leave form. Can also be a
    // larger fractional value (e.g. 1.5) for a "swapleave" record created
    // by convertExtraHoursToLeave, where an admin converts a non-whole
    // number of banked extra-hour days into a single swap-leave entry on
    // one date. Every place that used to do `Leave.countDocuments(...)` or
    // `leaves.length` to total up leave days must sum this field instead
    // (falling back to 1 for older records saved before this field
    // existed) — see getStaffCalendar, leaveBalance.js, and
    // payrollController.js.
    dayValue: {
      type: Number,
      default: 1,
      min: 0.5,
    },
    status: {
      type: String,
      enum: ["pending", "approved", "rejected"],
      default: "pending",
    },
    approvedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
    },
    approvedAt: {
      type: Date,
    },
    extraHoursSources: [
      {
        attendanceId: {
          type: mongoose.Schema.Types.ObjectId,
          ref: "Attendance",
          required: true,
        },
        deductedMinutes: {
          type: Number,
          required: true,
        },
      },
    ],
    // True for a day the system auto-created rather than a staff member
    // requesting it — either a "sandwich" day pulled in between two real
    // leave days, or an absent day with no attendance record that got
    // auto-marked as leave. See services/leaveAutomation.js.
    isAutoGenerated: {
      type: Boolean,
      default: false,
    },
    // Specifically a sandwich-leave day (subset of isAutoGenerated).
    isSandwich: {
      type: Boolean,
      default: false,
    },
    // For a sandwich day, the _id of the bracketing Leave that caused it to
    // be created — lets us cascade-delete the sandwich day if that source
    // leave is later deleted/reversed (see cleanupSandwichLeavesFor).
    sourceLeaveId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Leave",
      default: null,
    },
  },
  {
    timestamps: true,
  },
);

leaveSchema.index({ userId: 1, leaveDate: 1 });
leaveSchema.index({ leaveDate: 1 });

export default mongoose.model("Leave", leaveSchema);
